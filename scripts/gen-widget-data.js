// Copies the BS month lengths and festival list from www/index.html into the
// Android widget's Java data file, so the app and the widget always agree.
const fs = require('fs'), path = require('path');
const html = fs.readFileSync(path.join(__dirname, '..', 'www', 'index.html'), 'utf8');
const get = (name) => {
  const m = html.match(new RegExp('^const ' + name + '=(.*);\\s*$', 'm'));
  if (!m) throw new Error('Could not find ' + name + ' in www/index.html');
  return new Function('return (' + m[1] + ')')();
};
const BSD = get('BSD'), FEST = get('FEST'), FN = get('FN');
const years = Object.keys(BSD).map(Number).sort((a, b) => a - b);
const q = (s) => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const out = `// GENERATED by scripts/gen-widget-data.js from www/index.html. Do not edit by hand.
package com.kasign.kalendar;

final class BsData {
    static final int FIRST_YEAR = ${years[0]};
    static final int[][] MONTH_DAYS = {
${years.map((y) => '        {' + BSD[y].join(', ') + '}, // ' + y).join('\n')}
    };
    // {start, end, English name, Nepali name}
    static final String[][] FEST = {
${FEST.map((f) => '        {' + [f[0], f[1], f[2], FN[f[2]] || f[2]].map(q).join(', ') + '},').join('\n')}
    };
    private BsData() {}
}
`;
const dest = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'java', 'com', 'kasign', 'kalendar', 'BsData.java');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log('Wrote ' + dest + ' (' + years.length + ' BS years, ' + FEST.length + ' festivals)');
